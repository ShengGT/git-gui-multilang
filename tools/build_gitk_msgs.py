#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build gitk .msg catalogs from per-locale translation tables.

Translation tables live in gitk/translations/<locale>.json and map a source
index (as a string key of gitk/source_strings.json) to the translated text.
Keeping the English source out of the table keeps the files small and makes
sure the catalogs always follow the current gitk version.

Usage:
    python tools/build_gitk_msgs.py build            # build every locale
    python tools/build_gitk_msgs.py build zh_cn      # build one locale
    python tools/build_gitk_msgs.py import-legacy <msg> <locale>
    python tools/build_gitk_msgs.py report
"""
import io
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from po_tools import escape_tcl, parse_msg, read

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'gitk', 'source_strings.json')
TRANS = os.path.join(ROOT, 'gitk', 'translations')
OUT = os.path.join(ROOT, 'gitk', 'msgs')

HEADER = """\
# -*- coding: utf-8 -*-
# gitk message catalog: %(locale)s (%(native)s)
# Generated by tools/build_gitk_msgs.py - do not edit by hand.
# Source: gitk 2.x (git-gui Multilingual Pack)
# Translated: %(done)d/%(total)d
"""


def load_source():
    return json.loads(read(SRC))


def load_table(locale):
    path = os.path.join(TRANS, locale + '.json')
    if not os.path.exists(path):
        return {}
    data = json.loads(read(path))
    return {str(k): v for k, v in data.items() if isinstance(v, str) and v.strip()}


def load_meta():
    path = os.path.join(ROOT, 'languages.json')
    meta = {}
    if os.path.exists(path):
        for entry in json.loads(read(path))['locales']:
            meta[entry['locale']] = entry
    return meta


PLACEHOLDER = re.compile(r'%(?:\d+\$)?[sdif]')


def check(locale, en, tr, index, problems):
    if not tr:
        return
    if PLACEHOLDER.findall(en) and sorted(PLACEHOLDER.findall(en)) != sorted(PLACEHOLDER.findall(tr)):
        problems.append('%s [%s] placeholder mismatch: %r -> %r' % (locale, index, en, tr))
    if en.count('\n') != tr.count('\n') and '\n' in en:
        problems.append('%s [%s] newline count differs: %r -> %r' % (locale, index, en, tr))
    if tr == en and re.search(r'[A-Za-z]{3}', en):
        problems.append('%s [%s] identical to source: %r' % (locale, index, en))


def build(locale, keys, meta):
    table = load_table(locale)
    info = meta.get(locale, {})
    done = 0
    lines = []
    problems = []
    for i, en in enumerate(keys):
        tr = table.get(str(i), '')
        if tr:
            done += 1
            check(locale, en, tr, i, problems)
            lines.append('::msgcat::mcset %s "%s" "%s"' % (locale, escape_tcl(en), escape_tcl(tr)))
        else:
            lines.append('##::msgcat::mcset %s "%s" ""' % (locale, escape_tcl(en)))
    head = HEADER % {
        'locale': locale,
        'native': info.get('native', locale),
        'done': done,
        'total': len(keys),
    }
    if done == 0:
        # Nothing translated yet: keep the file tiny, gitk falls back to English.
        text = head + '\n# No translated strings for this locale yet.\n'
    else:
        text = head + '\n' + '\n'.join(lines) + '\n'
    out = os.path.join(OUT, locale + '.msg')
    io.open(out, 'w', encoding='utf-8', newline='\n').write(text)
    return done, len(keys), problems


def build_all(targets):
    keys = load_source()
    meta = load_meta()
    os.makedirs(OUT, exist_ok=True)
    rows = []
    problems = []
    for locale in targets:
        done, total, probs = build(locale, keys, meta)
        problems.extend(probs)
        rows.append((locale, done, total))
        print('%-8s %3d/%3d' % (locale, done, total))
    return rows, problems


def import_legacy(msg_path, locale):
    keys = load_source()
    old = dict(parse_msg(msg_path))
    table = {}
    for i, en in enumerate(keys):
        if en in old and old[en].strip():
            table[str(i)] = old[en]
    path = os.path.join(TRANS, locale + '.json')
    io.open(path, 'w', encoding='utf-8', newline='\n').write(
        json.dumps(table, ensure_ascii=False, indent=0, sort_keys=False))
    print('imported %d/%d strings from %s -> %s' % (len(table), len(keys), msg_path, path))


def patch(locale, patch_path):
    table = load_table(locale)
    overlay = json.loads(read(patch_path))
    keys = load_source()
    added = 0
    for k, v in overlay.items():
        k = str(k)
        if not v:
            table.pop(k, None)
            continue
        if k not in table:
            added += 1
        table[k] = v
    bad = [k for k in table if not k.isdigit() or int(k) >= len(keys)]
    path = os.path.join(TRANS, locale + '.json')
    io.open(path, 'w', encoding='utf-8', newline='\n').write(
        json.dumps(table, ensure_ascii=False, indent=0))
    print('%s: %d entries (%d new), invalid keys: %s' % (locale, len(table), added, bad or 'none'))


def report():
    keys = load_source()
    meta = load_meta()
    rows = []
    for locale in sorted(meta):
        table = load_table(locale)
        rows.append((locale, meta[locale].get('en', locale), len(table), len(keys)))
    lines = ['| Locale | Language | Translated | Total | Status |', '|---|---|---:|---:|---|']
    for locale, en, done, total in rows:
        status = 'complete' if done == total else ('partial' if done else 'missing')
        lines.append('| %s | %s | %d | %d | %s |' % (locale, en, done, total, status))
    out = os.path.join(ROOT, 'gitk', 'translation-status.md')
    io.open(out, 'w', encoding='utf-8', newline='\n').write(
        '# gitk translation status\n\n' + '\n'.join(lines) + '\n')
    complete = sum(1 for r in rows if r[2] == r[3])
    print('%d/%d locales complete -> %s' % (complete, len(rows), out))


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'help'
    if cmd == 'build':
        meta = load_meta()
        targets = sys.argv[2:] or sorted(meta)
        rows, problems = build_all(targets)
        for p in problems:
            print('WARN ' + p)
    elif cmd == 'import-legacy':
        import_legacy(sys.argv[2], sys.argv[3])
    elif cmd == 'patch':
        patch(sys.argv[2], sys.argv[3])
    elif cmd == 'report':
        report()
    else:
        print(__doc__)


if __name__ == '__main__':
    main()
